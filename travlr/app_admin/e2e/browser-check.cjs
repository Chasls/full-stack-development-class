'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require('playwright');
const { connect, disconnect } = require('../../app_api/models/db');
const Trip = require('../../app_api/models/travlr');
const base = process.env.BASE_URL || 'http://localhost:3000';
const output = path.resolve(__dirname, '../../../submission/module6');
const sample = { code: 'ISLAND-ESCAPE', name: 'Island Escape', length: '7 days', start: '2027-09-18', resort: 'Travlr Island Resort', perPerson: '$1,399', image: 'reef1.jpg', description: '<p>Explore quiet beaches, snorkel through colorful coral, and enjoy a sunset cruise during seven days at Travlr Island Resort.</p>' };
(async () => {
  fs.mkdirSync(output, { recursive: true });
  await connect();
  assert.equal(await Trip.countDocuments({ code: sample.code }), 0, 'ISLAND-ESCAPE already exists; use a fresh database before rerunning the demo.');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/admin/');
    await page.getByRole('heading', { name: 'Your getaways' }).waitFor();
    await page.getByRole('link', { name: 'Add trip', exact: true }).click();
    await page.getByRole('button', { name: 'Add trip', exact: true }).click();
    await page.getByRole('alert').filter({ hasText: 'Complete every field' }).waitFor();
    for (const field of ['code', 'name', 'length', 'start', 'resort', 'perPerson', 'description']) await page.locator('#' + field).fill(sample[field]);
    await page.locator('#image').selectOption(sample.image);
    await page.getByRole('button', { name: 'Add trip', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Island Escape added successfully.' }).waitFor();
    await page.getByRole('heading', { name: 'Island Escape', exact: true }).waitFor();
    const card = page.locator('app-trip-card').filter({ hasText: 'ISLAND-ESCAPE' });
    assert.equal((await Trip.findOne({ code: sample.code })).name, sample.name);
    assert.match(await (await fetch(base + '/travel')).text(), /Island Escape/);
    await page.screenshot({ path: path.join(output, '01-card-listing-added-trip.png'), fullPage: true });
    await card.getByRole('link', { name: 'Edit trip' }).click();
    await page.locator('#name').waitFor();
    assert.equal(await page.locator('#name').inputValue(), sample.name);
    assert.equal(await page.locator('#code').getAttribute('readonly'), '');
    await page.screenshot({ path: path.join(output, '02-edit-screen.png'), fullPage: true });
    await page.locator('#name').fill('Island Escape Adventure');
    await page.locator('#perPerson').fill('$1,499');
    await page.getByRole('button', { name: 'Save changes' }).click();
    await page.getByRole('status').filter({ hasText: 'Island Escape Adventure updated successfully.' }).waitFor();
    await page.getByRole('heading', { name: 'Island Escape Adventure', exact: true }).waitFor();
    assert.equal((await Trip.findOne({ code: sample.code })).perPerson, '$1,499');
    await page.screenshot({ path: path.join(output, '03-update-screen.png'), fullPage: true });
    await card.getByRole('link', { name: 'Edit trip' }).click();
    await page.locator('#name').waitFor();
    assert.equal(await page.locator('#name').inputValue(), 'Island Escape Adventure');
    await page.reload();
    await page.locator('#name').waitFor();
    assert.equal(await page.locator('#perPerson').inputValue(), '$1,499');
    await page.getByRole('link', { name: 'Cancel', exact: true }).click();
    await card.getByRole('button', { name: 'Delete', exact: true }).click();
    await page.getByRole('button', { name: 'Cancel', exact: true }).click();
    assert.ok(await Trip.findOne({ code: sample.code }));
    const temporary = { ...sample, code: 'BROWSER-DELETE-TEST', start: sample.start + 'T00:00:00.000Z', name: 'Temporary Browser Trip' };
    const added = await fetch(base + '/api/trips', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(temporary) });
    assert.equal(added.status, 201);
    await page.reload();
    const tempCard = page.locator('app-trip-card').filter({ hasText: temporary.code });
    await tempCard.getByRole('button', { name: 'Delete', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm delete' }).click();
    await page.getByRole('status').filter({ hasText: 'Temporary Browser Trip deleted.' }).waitFor();
    assert.equal(await Trip.findOne({ code: temporary.code }), null);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.reload();
    await page.getByRole('heading', { name: 'Island Escape Adventure', exact: true }).waitFor();
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page must not overflow horizontally');
    await page.screenshot({ path: path.join(output, '04-mobile-card-listing.png'), fullPage: true });
    const publicPage = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    await publicPage.goto(base + '/travel');
    await publicPage.getByRole('heading', { name: 'Island Escape Adventure', exact: true }).waitFor();
    await publicPage.screenshot({ path: path.join(output, '05-public-website.png'), fullPage: true });
    assert.deepEqual(errors, []);
    const stored = await Trip.findOne({ code: sample.code }).select('-_id -__v').lean();
    fs.writeFileSync(path.resolve(__dirname, '../../data/module6-added-trip.json'), JSON.stringify([stored], null, 2) + '\n');
    fs.writeFileSync(path.join(output, 'browser-test-results.json'), JSON.stringify({ passed: true, checks: ['required fields', 'add through Angular', 'MongoDB persistence', 'public-site rendering', 'edit preload', 'update through Angular', 'refresh and deep-link route', 'cancel deletion', 'confirmed deletion', 'mobile layout', 'no browser script errors'] }, null, 2) + '\n');
    console.log('Browser workflow passed; screenshots saved to ' + output);
  } finally { await browser.close(); await disconnect(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
