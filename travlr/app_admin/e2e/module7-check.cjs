'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawn, execSync } = require('node:child_process');
const { chromium } = require('playwright');
const { connect, disconnect, mongoose } = require('../../app_api/models/db');
const User = require('../../app_api/models/user');
const Trip = require('../../app_api/models/travlr');
const { seedTrips } = require('../../app_api/models/seed');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'test/evidence/module7');
const base = 'http://127.0.0.1:3107';
const uri = `mongodb://127.0.0.1:27017/travlr_module7_e2e_${process.pid}_${Date.now()}`;
const sample = {code: 'SECURE-BROWSER-TRIP', name: 'Secure Island Escape', length: '7 days', start: '2027-09-18', resort: 'Travlr Island Resort', perPerson: '$1,399', image: 'reef1.jpg', description: '<p>Seven days of beaches and snorkeling.</p>'};
let server, browser;
(async () => {
 fs.mkdirSync(output, {recursive: true});
 await connect(uri); await seedTrips();
 const admin = new User({name: 'Mock Admin', email: 'admin@example.test', role: 'admin'});
 await admin.setPassword('Mock-password-2026!'); await admin.save();
 server = spawn(process.execPath, ['server.js'], {cwd: root, env: {...process.env, PORT: '3107', MONGODB_URI: uri, JWT_SECRET: 'module-seven-browser-test-secret-2026'}, stdio: 'pipe'});
 let ready = false;
 for(let i=0; i<100; i++) {
  try { if ((await fetch(base + '/health')).ok) {ready = true; break;} } catch {}
  await new Promise(resolve => setTimeout(resolve, 100));
 }
 assert.ok(ready, 'Test server must start');
 execSync('npx.cmd --yes newman run test/Travlr_API.postman_collection.json --env-var baseUrl=http://127.0.0.1:3107 --reporters cli,json --reporter-json-export test/evidence/module7/postman-results.json', {cwd: root, stdio: 'inherit'});
 browser = await chromium.launch({channel: 'chrome', headless: true});
 const page = await browser.newPage({viewport: {width: 1440, height: 1000}});
 const errors = []; page.on('pageerror', error => errors.push(error.message));
 await page.goto(base + '/admin/'); await page.getByRole('heading', {name: 'Your getaways'}).waitFor();
 assert.equal(await page.getByRole('link', {name: 'Add trip', exact: true}).count(), 0);
 assert.equal(await page.getByRole('link', {name: 'Edit trip'}).count(), 0);
 assert.equal(await page.getByRole('button', {name: 'Delete', exact: true}).count(), 0);
 await page.screenshot({path: path.join(output, '01-logged-out.png'), fullPage: true});
 await page.goto(base + '/admin/trips/new'); await page.getByRole('heading', {name: 'Administrator login'}).waitFor();
 await page.locator('#email').fill('admin@example.test'); await page.locator('#password').fill('wrong');
 await page.getByRole('button', {name: 'Log in', exact: true}).click();
 await page.getByRole('alert').filter({hasText: 'Email or password is incorrect'}).waitFor();
 await page.screenshot({path: path.join(output, '02-login-rejected.png'), fullPage: true});
 await page.locator('#password').fill('Mock-password-2026!'); await page.getByRole('button', {name: 'Log in', exact: true}).click();
 await page.locator('#code').waitFor();
 for(const field of ['code', 'name', 'length', 'start', 'resort', 'perPerson', 'description']) await page.locator('#'+field).fill(sample[field]);
 await page.locator('#image').selectOption(sample.image);
 await page.getByRole('button', {name: 'Add trip', exact: true}).click();
 await page.getByRole('status').filter({hasText: 'Secure Island Escape added successfully.'}).waitFor();
 assert.ok(await Trip.findOne({code: sample.code}));
 await page.screenshot({path: path.join(output, '03-authenticated-crud.png'), fullPage: true});
 const card = page.locator('app-trip-card').filter({hasText: sample.code});
 await card.getByRole('link', {name: 'Edit trip'}).click(); await page.locator('#name').waitFor();
 await page.locator('#name').fill('Updated Secure Escape'); await page.getByRole('button', {name: 'Save changes'}).click();
 await page.getByRole('status').filter({hasText: 'Updated Secure Escape updated successfully.'}).waitFor();
 await page.reload(); await card.getByRole('heading', {name: 'Updated Secure Escape'}).waitFor();
 assert.equal((await Trip.findOne({code: sample.code})).name, 'Updated Secure Escape');
 assert.match(await (await fetch(base + '/travel')).text(), /Updated Secure Escape/);
 await page.screenshot({path: path.join(output, '04-update-persisted.png'), fullPage: true});
 await card.getByRole('button', {name: 'Delete', exact: true}).click(); await page.getByRole('button', {name: 'Cancel', exact: true}).click();
 assert.ok(await Trip.findOne({code: sample.code}));
 await card.getByRole('button', {name: 'Delete', exact: true}).click(); await page.getByRole('button', {name: 'Confirm delete'}).click();
 await page.getByRole('status').filter({hasText: 'Updated Secure Escape deleted.'}).waitFor();
 assert.equal(await Trip.findOne({code: sample.code}), null);
 await page.getByRole('button', {name: 'Log out', exact: true}).click(); await page.getByRole('heading', {name: 'Administrator login'}).waitFor();
 assert.equal(await page.evaluate(() => sessionStorage.getItem('travlr-token')), null);
 await page.goto(base + '/admin/trips/GALE-REEF/edit'); await page.getByRole('heading', {name: 'Administrator login'}).waitFor();
 await page.setViewportSize({width: 390, height: 844});
 assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
 await page.screenshot({path: path.join(output, '05-mobile-login.png'), fullPage: true});
 // A forged expired token cannot enable controls or bypass the guard.
 await page.evaluate(() => sessionStorage.setItem('travlr-token', 'header.' + btoa(JSON.stringify({role: 'admin', exp: 1})) + '.signature'));
 await page.goto(base + '/admin/'); await page.getByRole('heading', {name: 'Your getaways'}).waitFor();
 assert.equal(await page.getByRole('link', {name: 'Edit trip'}).count(), 0);
 assert.deepEqual(errors, []);
 fs.writeFileSync(path.join(output, 'browser-results.json'), JSON.stringify({passed: true, checks: ['anonymous controls hidden', 'direct add route guarded', 'wrong password rejected', 'administrator login', 'authenticated create', 'edit and refresh persistence', 'public website reflects update', 'cancel deletion', 'authenticated delete', 'logout clears token', 'direct edit route guarded', 'mobile login layout', 'expired session hides controls', 'no browser script errors']}, null, 2));
 console.log('Module Seven browser checks passed.');
})().catch(error => {console.error(error); process.exitCode = 1;}).finally(async () => {
 if(browser) await browser.close();
 if(server) {server.kill(); await new Promise(resolve => server.once('exit', resolve));}
 if(mongoose.connection.readyState === 1) await mongoose.connection.dropDatabase();
 await disconnect();
});
